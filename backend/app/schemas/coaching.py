"""
Pydantic Schemas for Interactive Multi-Turn Coaching Workflows.
Defines educational modes, progression stages, and diagnostic evaluations.
"""
from enum import Enum
from typing import List, Optional
from pydantic import BaseModel, Field, ConfigDict


class CoachingMode(str, Enum):
    """Pedagogical stances for the AI tutor."""
    SOCRATIC = "socratic"        # Guides through targeted questioning; avoids giving direct answers
    EXPLANATORY = "explanatory"  # Deep conceptual explanations with analogies and breakdowns
    QUIZ = "quiz"                # Rapid active recall testing and knowledge verification
    REVIEW = "review"            # Critiques student work, identifies misconceptions, refines solutions


class CoachingStage(str, Enum):
    """Progressive stages in a multi-turn coaching session."""
    ASSESSMENT = "assessment"    # Gauging baseline knowledge and prerequisites
    EXPLANATION = "explanation"  # Introducing and deconstructing core concepts
    PRACTICE = "practice"        # Guided problem-solving and application
    SUMMARY = "summary"          # Consolidating key takeaways and reflection
    COMPLETED = "completed"      # Session objectives satisfied


class CoachingEvaluation(BaseModel):
    """Diagnostic evaluation generated by the AI coach for each turn."""
    understanding_score: int = Field(
        ...,
        ge=1,
        le=5,
        description="Assessed student comprehension level for this turn (1=None/Confused, 5=Mastered)."
    )
    concept_mastered: bool = Field(
        ...,
        description="True if the student demonstrated complete mastery of the current target concept."
    )
    feedback: str = Field(
        ...,
        description="Constructive, encouraging feedback on the student's reasoning and response."
    )
    hints: List[str] = Field(
        default_factory=list,
        description="Scaffolded hints if the student is struggling."
    )
    next_step: str = Field(
        ...,
        description="Recommended next pedagogical action."
    )

    model_config = ConfigDict(
        json_schema_extra={
            "example": {
                "understanding_score": 4,
                "concept_mastered": False,
                "feedback": "Great intuition on time complexity, but consider edge cases with empty arrays.",
                "hints": ["What happens if the input list contains duplicate elements?"],
                "next_step": "Guide student to refine worst-case space complexity analysis."
            }
        }
    )


class CoachingTurnPayload(BaseModel):
    """Internal model for Gemini structured JSON output parsing."""
    assistant_message: str = Field(
        ...,
        description="The conversational pedagogical response directed to the student."
    )
    evaluation: CoachingEvaluation = Field(
        ...,
        description="Diagnostic assessment and feedback metadata."
    )
    suggested_replies: List[str] = Field(
        default_factory=list,
        max_length=3,
        description="2-3 recommended quick response options for the student."
    )


class CoachingTurnRequest(BaseModel):
    """Request payload for an interactive coaching turn."""
    message: str = Field(
        ...,
        min_length=1,
        max_length=5000,
        description="Student's message, answer, or question.",
        examples=["Binary search divides the search space in half each step, giving O(log n)."]
    )
    topic: str = Field(
        ...,
        min_length=2,
        max_length=200,
        description="Subject matter or concept being coached.",
        examples=["Binary Search Algorithm"]
    )
    mode: CoachingMode = Field(
        default=CoachingMode.SOCRATIC,
        description="Pedagogical stance for the AI coach."
    )
    stage: CoachingStage = Field(
        default=CoachingStage.PRACTICE,
        description="Current stage in the learning workflow."
    )
    target_objectives: List[str] = Field(
        default_factory=list,
        description="List of specific learning objectives to achieve."
    )


class CoachingTurnResponse(BaseModel):
    """Response returned to the client after a coaching turn."""
    session_id: str = Field(..., description="Active chat session identifier")
    mode: CoachingMode = Field(..., description="Pedagogical mode used")
    stage: CoachingStage = Field(..., description="Current learning stage")
    assistant_message: str = Field(..., description="Conversational reply from the tutor")
    evaluation: CoachingEvaluation = Field(..., description="Real-time comprehension evaluation")
    suggested_replies: List[str] = Field(
        default_factory=list,
        description="Suggested quick-reply prompt options"
    )
    tokens_used: int = Field(default=0, description="Estimated token count")